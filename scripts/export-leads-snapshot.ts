/**
 * One file, every lead, with lifecycle state and fit grade already computed.
 * The feed for an agent that reads the lead dashboard's data without being the
 * dashboard.
 *
 *   npm run snapshot:leads              # exports both deployments, then builds
 *   npm run snapshot:leads -- --offline # rebuilds from the last raw export
 *
 * Writes `data/agent/leads-snapshot.json`. That directory is inside the app
 * repo's gitignored `data/` on purpose: this file holds real names, emails,
 * LINE IDs and phone numbers, and `data-inventory.md` is the record that it
 * exists. It must never be copied into the coaching repo, whose own gitignore
 * says in as many words that the method lives there and the people do not.
 *
 * **Nothing here decides anything.** State comes from `src/lib/lifecycle.ts`,
 * fit from `src/lib/leadGrade.ts`, scores from `convex/scoring.ts` and consent
 * from `src/lib/consent.ts`, imported and called. A rule reimplemented here
 * would be a second answer to a question that already has one, which is the
 * failure `leads.scores` and the stored `lifecycleStage` were both removed to
 * avoid. If a rule changes, re-run this; do not edit this file.
 *
 * **Both deployments, tagged.** `dashing-shepherd-41` is production and
 * `quiet-mule-251` is development, and dev is not a scratch environment: the 90
 * leads imported from the Lead Discovery Survey on 10/08/2026 are in it,
 * because production did not exist for another four days
 * (`data-inventory.md` § 1). A production-only snapshot silently drops them.
 *
 * **`personId` groups the same human across deployments.** It is a hash of the
 * lowercased email and nothing else, so it is stable between runs, reveals
 * nothing on its own, and gives an agent one key to group on instead of each
 * of them inventing a de-duplication rule. 92 people are currently in both
 * stores; counting rows without grouping overstates the pipeline.
 *
 * The header carries each deployment's row count and its most recent activity
 * date, which is the empirical answer to the standing Vercel question: if
 * `NEXT_PUBLIC_CONVEX_URL` is still scoped to Production, live traffic lands in
 * dev, and the giveaway is dev having fresher activity than prod. That case
 * emits a warning into the header rather than being left for someone to notice.
 *
 * **Temperature ships since 19/08/2026**, computed by `src/lib/temperature.ts`
 * from `08_Coaching_Business.md`'s recovered weights (TASK-055). Read it beside
 * Fit and never multiplied by it: that document keeps them independent axes on
 * purpose. Its own doc comment records what the port could not carry across,
 * and `temperature.unmeasured` repeats it per lead.
 */

